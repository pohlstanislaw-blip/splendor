// Balance simulation: thousands of Medium-AI games at 2, 3 and 4 players.
//
//   npm run simulate                 # 1000 games per player count, print report
//   npm run simulate -- --games 3000 # more games
//   npm run simulate -- --write      # also refresh the generated section of BALANCE.md
//
// Reports seat win rates (relative to the starting player), game length, per-card purchase rate and
// "win lift" (how much more often players who bought a card won than an average player), per-colour
// stats and patron claim rates. Cards are also aggregated by cost pattern, because the data is
// symmetric across colours: tuning happens per pattern, applied to all five colours at once.
import { readFileSync, writeFileSync } from 'node:fs';
import { applyAction, chooseAiAction, createGame, type GameState } from '../src/engine';
import { CARDS, PATRONS, TIER_NAMES } from '../src/engine/data';
import { cardShape, checkDesignRules, totalCost } from '../src/engine/designRules';
import { GEMS, type Card, type Tier } from '../src/engine/types';

const args = process.argv.slice(2);
const GAMES = Number(args[args.indexOf('--games') + 1]) || 1000;
const WRITE = args.includes('--write');
const STEP_CAP = 4000;

interface CardStat { seen: number; bought: number; holders: number; holderWins: number; holderExpected: number }
const cardStats = new Map<string, CardStat>(CARDS.map((c) => [c.id, { seen: 0, bought: 0, holders: 0, holderWins: 0, holderExpected: 0 }]));
const patronStats = new Map<string, { revealed: number; claimed: number }>(PATRONS.map((p) => [p.id, { revealed: 0, claimed: 0 }]));
const seatStats: Record<number, { wins: number[]; games: number; rounds: number; capped: number; turnsToEnd: number[] }> = {};

// simple LCG for the AI's fallback randomness
let r = 12345;
const rand = () => ((r = (r * 1103515245 + 12345) % 2147483648) / 2147483648);

const t0 = Date.now();
for (const n of [2, 3, 4]) {
  const ss = (seatStats[n] = { wins: Array(n).fill(0), games: 0, rounds: 0, capped: 0, turnsToEnd: [] });
  for (let g = 0; g < GAMES; g++) {
    let s: GameState = createGame(
      Array.from({ length: n }, (_, i) => ({ name: `AI${i}`, controller: 'medium' as const })),
      n * 1_000_003 + g * 7919 + 1,
    );
    for (const id of s.patrons) patronStats.get(id)!.revealed++;
    const seen = new Set<string>();
    const markSeen = () => {
      for (const row of s.market) for (const id of row) if (id) seen.add(id);
      for (const p of s.players) for (const rc of p.reserved) seen.add(rc.cardId);
    };
    markSeen();
    let steps = 0;
    while (s.phase !== 'gameover' && steps < STEP_CAP) {
      s = applyAction(s, chooseAiAction(s, rand));
      markSeen();
      steps++;
    }
    ss.games++;
    if (s.phase !== 'gameover') {
      ss.capped++;
      continue;
    }
    ss.rounds += s.round;
    for (const id of seen) cardStats.get(id)!.seen++;
    for (const w of s.winners) ss.wins[(w - s.startPlayer + n) % n] += 1 / s.winners.length;
    s.players.forEach((p, i) => {
      const winShare = s.winners.includes(i) ? 1 / s.winners.length : 0;
      for (const id of p.cards) {
        const st = cardStats.get(id)!;
        st.bought++;
        st.holders++;
        st.holderWins += winShare;
        st.holderExpected += 1 / n;
      }
      for (const id of p.patrons) patronStats.get(id)!.claimed++;
    });
  }
}
const elapsed = ((Date.now() - t0) / 1000).toFixed(1);

// ---------------------------------------------------------------------------
// Report
// ---------------------------------------------------------------------------
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const f2 = (x: number) => x.toFixed(2);
const out: string[] = [];
const say = (s = '') => out.push(s);

say(`_${GAMES} Medium-AI games per player count (${GAMES * 3} total), generated by \`npm run simulate -- --games ${GAMES} --write\` in ${elapsed}s._`);
say();
const problems = checkDesignRules(CARDS, PATRONS);
say(`Design rules: ${problems.length ? `**${problems.length} violation(s)**: ${problems.join('; ')}` : 'all pass ✓'}`);
say();

say('### Seats and game length');
say();
say('Seat 1 is the starting player. A fair seat wins 1/N of games.');
say();
say('| Players | Seat 1 | Seat 2 | Seat 3 | Seat 4 | Starting-player edge | Max seat deviation | Avg rounds | Unfinished |');
say('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
const flags: string[] = [];
for (const n of [2, 3, 4]) {
  const ss = seatStats[n];
  const done = ss.games - ss.capped;
  const rates = ss.wins.map((w) => w / done);
  const dev = Math.max(...rates.map((x) => Math.abs(x - 1 / n)));
  const edge = rates[0] - 1 / n;
  if (edge > 0.03) flags.push(`${n}p starting-player edge ${pct(edge)}`);
  if (dev > 0.05) flags.push(`${n}p seat imbalance ${pct(dev)}`);
  const cells = [0, 1, 2, 3].map((i) => (i < n ? pct(rates[i]) : '—'));
  say(`| ${n} | ${cells.join(' | ')} | ${edge >= 0 ? '+' : ''}${(edge * 100).toFixed(1)} pp | ${(dev * 100).toFixed(1)} pp | ${f2(ss.rounds / done)} | ${ss.capped} |`);
}
say();

// per pattern
interface Agg { cards: Card[]; seen: number; bought: number; wins: number; expected: number }
const byPattern = new Map<string, Agg>();
for (const c of CARDS) {
  const key = `T${c.tier} ${cardShape(c)}`;
  const a = byPattern.get(key) ?? { cards: [], seen: 0, bought: 0, wins: 0, expected: 0 };
  const st = cardStats.get(c.id)!;
  a.cards.push(c);
  a.seen += st.seen;
  a.bought += st.bought;
  a.wins += st.holderWins;
  a.expected += st.holderExpected;
  byPattern.set(key, a);
}
const tierAvg = (tier: Tier) => {
  const cs = CARDS.filter((c) => c.tier === tier).map((c) => cardStats.get(c.id)!);
  return {
    buy: cs.reduce((s, x) => s + x.bought, 0) / cs.reduce((s, x) => s + x.seen, 0),
    lift: cs.reduce((s, x) => s + x.holderWins, 0) / cs.reduce((s, x) => s + x.holderExpected, 0),
  };
};

say('### Cost patterns (each row is the same card in all 5 colours)');
say();
say('**Buy rate** is the share of games where the card was dealt or reserved and someone bought it, compared with the average for its tier. **Win lift** is how often players holding the card won, divided by how often an average player wins. Rows outside 0.6–1.4× the tier buy rate, or more than ±0.15 from the tier win lift, are flagged ⚠.');
say();
say('| Tier | Pattern | Example | Cost | Buy rate | vs tier | Win lift | vs tier |');
say('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const tier of [1, 2, 3] as Tier[]) {
  const avg = tierAvg(tier);
  for (const [key, a] of [...byPattern].filter(([k]) => k.startsWith(`T${tier}`))) {
    const buy = a.bought / a.seen;
    const lift = a.wins / a.expected;
    const rel = buy / avg.buy;
    const liftDiff = lift - avg.lift;
    const flag = rel < 0.6 || rel > 1.4 || Math.abs(liftDiff) > 0.15 ? ' ⚠' : '';
    if (flag) flags.push(`${key}: buy ×${f2(rel)}, lift ${liftDiff >= 0 ? '+' : ''}${f2(liftDiff)}`);
    const ex = a.cards[0];
    const cost = GEMS.filter((g) => ex.cost[g]).map((g) => `${ex.cost[g]} ${g}`).join(', ');
    say(`| ${tier} | ${key.slice(3)}${flag} | ${ex.name} | ${cost} (${totalCost(ex)}) | ${pct(buy)} | ×${f2(rel)} | ${f2(lift)} | ${liftDiff >= 0 ? '+' : ''}${f2(liftDiff)} |`);
  }
  say(`| ${tier} | **${TIER_NAMES[tier]} average** | | | ${pct(avg.buy)} | | ${f2(avg.lift)} | |`);
}
say();

say('### Colours');
say();
say('| Colour | Cards bought | Share | Win lift of holders |');
say('| --- | --- | --- | --- |');
const totalBought = [...cardStats.values()].reduce((s, x) => s + x.bought, 0);
for (const g of GEMS) {
  const cs = CARDS.filter((c) => c.bonus === g).map((c) => cardStats.get(c.id)!);
  const bought = cs.reduce((s, x) => s + x.bought, 0);
  const lift = cs.reduce((s, x) => s + x.holderWins, 0) / cs.reduce((s, x) => s + x.holderExpected, 0);
  if (Math.abs(bought / totalBought - 0.2) > 0.02) flags.push(`colour ${g} share ${pct(bought / totalBought)}`);
  say(`| ${g} | ${bought} | ${pct(bought / totalBought)} | ${f2(lift)} |`);
}
say();

say('### Patrons');
say();
say('| Patron | Requires | Revealed | Claimed | Claim rate |');
say('| --- | --- | --- | --- | --- |');
for (const p of PATRONS) {
  const st = patronStats.get(p.id)!;
  say(`| ${p.name} | ${Object.entries(p.requires).map(([g, k]) => `${k} ${g}`).join(' + ')} | ${st.revealed} | ${st.claimed} | ${pct(st.claimed / st.revealed)} |`);
}
say();

say('### Every card');
say();
say('<details><summary>Per-card buy rate and win lift (90 cards)</summary>');
say();
say('| Card | Tier | Bonus | Pts | Cost | Seen | Buy rate | Win lift |');
say('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const c of CARDS) {
  const st = cardStats.get(c.id)!;
  const cost = GEMS.filter((g) => c.cost[g]).map((g) => `${c.cost[g]}${g[0].toUpperCase()}`).join(' ');
  say(`| ${c.name} | ${c.tier} | ${c.bonus} | ${c.points} | ${cost} | ${st.seen} | ${pct(st.bought / Math.max(1, st.seen))} | ${f2(st.holderWins / Math.max(1e-9, st.holderExpected))} |`);
}
say();
say('</details>');
say();
say(flags.length ? `**Flags (${flags.length}):** ${flags.join('; ')}` : '**No flags:** every pattern is within range, colours are even, the starting-player edge is within 3 pp and every seat is within 5 pp of fair.');

const report = out.join('\n');
console.log(report);

if (WRITE) {
  const path = 'BALANCE.md';
  let doc = '';
  try {
    doc = readFileSync(path, 'utf8');
  } catch {
    doc = '# Balance\n\n<!-- sim:start -->\n<!-- sim:end -->\n';
  }
  const start = doc.indexOf('<!-- sim:start -->');
  const end = doc.indexOf('<!-- sim:end -->');
  if (start < 0 || end < 0) throw new Error('BALANCE.md is missing the <!-- sim:start --> / <!-- sim:end --> markers');
  writeFileSync(path, doc.slice(0, start) + '<!-- sim:start -->\n' + report + '\n' + doc.slice(end));
  console.error(`\nUpdated ${path}`);
}
